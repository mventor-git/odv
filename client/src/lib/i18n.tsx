export type Lang = 'en' | 'ar';

interface I18nState {
  lang: Lang;
  dir: 'ltr' | 'rtl';
  setLang: (l: Lang) => void;
  t: (key: keyof typeof en) => string;
}

const I18nContext = createContext<I18nState | null>(null);

export function I18nProvider({ children }: { children: ReactNode }): ReactNode {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('odv_lang');
    return saved === 'ar' ? 'ar' : 'en';
  });

  const dir: 'ltr' | 'rtl' = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    // Smooth full-page transition so user sees the AR↔EN switch
    document.documentElement.classList.add('page-switching');
    const id = window.setTimeout(() => document.documentElement.classList.remove('page-switching'), 500);
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    localStorage.setItem('odv_lang', lang);
    return () => window.clearTimeout(id);
  }, [lang, dir]);

  const value = useMemo<I18nState>(
    () => ({
      lang,
      dir,
      setLang: (l) => setLangState(l),
      t: (key) => (lang === 'ar' ? ar[key] : en[key]) ?? key,
    }),
    [lang, dir],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nState {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

/** Collect every `export.*` key in both languages into a compact bundle that the
 *  server's standalone-report builder uses — so NO report strings are hardcoded
 *  server-side; they are editable here like any other UI string (ticket 133). */
export function buildExportStrings(): { en: Record<string, string>; ar: Record<string, string> } {
  const pick = (dict: Record<string, string>): Record<string, string> => {
    const out: Record<string, string> = {};
    for (const k of Object.keys(dict)) {
      if (k.startsWith('export.')) out[k] = dict[k];
    }
    return out;
  };
  return { en: pick(en), ar: pick(ar) };
}
